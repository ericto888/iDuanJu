// Python side of the host, run once right after the interpreter starts. Own code.
#ifndef IDJ_BOOT_H
#define IDJ_BOOT_H

static const char idj_boot_source[] =
    "import io, json, os, sys, threading, traceback, warnings\n"
    "import _idj_host as host\n"
    "\n"
    "warnings.simplefilter(\"ignore\")\n"
    "\n"
    "\n"
    "class LogBytes(io.RawIOBase):\n"
    "    \"\"\"sys.stdout.buffer\"\"\"\n"
    "\n"
    "    def __init__(self, log):\n"
    "        super().__init__()\n"
    "        self._log = log\n"
    "\n"
    "    def writable(self):\n"
    "        return True\n"
    "\n"
    "    def write(self, data):\n"
    "        data = bytes(data)\n"
    "        self._log.write(data.decode(\"utf-8\", \"replace\"))\n"
    "        return len(data)\n"
    "\n"
    "    def close(self):\n"
    "        pass\n"
    "\n"
    "\n"
    "class Log(io.TextIOBase):\n"
    "    \"\"\"print() and stderr -> host log, one call per line, buffered per thread.\"\"\"\n"
    "    encoding = \"utf-8\"\n"
    "    errors = \"replace\"\n"
    "\n"
    "    def __init__(self):\n"
    "        super().__init__()\n"
    "        self._local = threading.local()\n"
    "        self.buffer = LogBytes(self)\n"
    "\n"
    "    def writable(self):\n"
    "        return True\n"
    "\n"
    "    def isatty(self):\n"
    "        return False\n"
    "\n"
    "    def reconfigure(self, **kwargs):\n"
    "        pass\n"
    "\n"
    "    def close(self):\n"
    "        pass\n"
    "\n"
    "    def write(self, text):\n"
    "        if not isinstance(text, str):\n"
    "            raise TypeError(\"write() argument must be str, not \" + type(text).__name__)\n"
    "        buf = getattr(self._local, \"buf\", \"\") + text\n"
    "        *lines, buf = buf.split(\"\\n\")\n"
    "        if len(buf) > 4000:\n"
    "            lines.append(buf)\n"
    "            buf = \"\"\n"
    "        self._local.buf = buf\n"
    "        for line in lines:\n"
    "            emit(line)\n"
    "        return len(text)\n"
    "\n"
    "    def flush(self):\n"
    "        buf = getattr(self._local, \"buf\", \"\")\n"
    "        if buf:\n"
    "            self._local.buf = \"\"\n"
    "            emit(buf)\n"
    "\n"
    "\n"
    "def emit(line):\n"
    "    if line.strip():\n"
    "        try:\n"
    "            host.call(\"log\", json.dumps({\"m\": line[:4000]}))\n"
    "        except Exception:\n"
    "            pass\n"
    "\n"
    "\n"
    "def flush():\n"
    "    sys.stdout.flush()\n"
    "    sys.stderr.flush()\n"
    "\n"
    "\n"
    "sys.stdin = sys.__stdin__ = io.StringIO()\n"
    "sys.stdout = sys.__stdout__ = Log()\n"
    "sys.stderr = sys.__stderr__ = Log()\n"
    "\n"
    "\n"
    "# Threads inherit the spider key of the thread that starts them, and can be interrupted together with it.\n"
    "def patch_threads():\n"
    "    cls = threading.Thread\n"
    "    start, inner, hook = cls.start, cls._bootstrap_inner, threading.excepthook\n"
    "\n"
    "    def idj_start(self):\n"
    "        self._idj_context = host.context()\n"
    "        return start(self)\n"
    "\n"
    "    def idj_inner(self):\n"
    "        context = getattr(self, \"_idj_context\", None)\n"
    "        if context is None:\n"
    "            return inner(self)\n"
    "        host.enter(*context)\n"
    "        try:\n"
    "            inner(self)\n"
    "        finally:\n"
    "            host.leave()\n"
    "\n"
    "    def idj_hook(args):\n"
    "        if not (args.exc_type and issubclass(args.exc_type, host.Interrupted)):\n"
    "            hook(args)\n"
    "\n"
    "    cls.start, cls._bootstrap_inner, threading.excepthook = idj_start, idj_inner, idj_hook\n"
    "\n"
    "\n"
    "patch_threads()\n"
    "\n"
    "\n"
    "# A script must not be able to end the app by accident.\n"
    "def denied(*args, **kwargs):\n"
    "    raise PermissionError(\"not available to scripts\")\n"
    "\n"
    "\n"
    "for name in (\"_exit\", \"abort\", \"kill\", \"killpg\"):\n"
    "    if hasattr(os, name):\n"
    "        setattr(os, name, denied)\n"
    "\n"
    "\n"
    "def describe(exc):\n"
    "    \"\"\"(one line, full traceback)\"\"\"\n"
    "    try:\n"
    "        full = \"\".join(traceback.format_exception(type(exc), exc, exc.__traceback__))\n"
    "    except Exception:\n"
    "        full = repr(type(exc))\n"
    "    try:\n"
    "        text = \" \".join(str(exc).split())\n"
    "    except Exception:\n"
    "        text = \"\"\n"
    "    line = type(exc).__name__ + (\": \" + text if text else \"\")\n"
    "    return line[:500], full[-20000:]\n"
    "\n"
    "\n"
    "def add_path(path):\n"
    "    if path not in sys.path:\n"
    "        sys.path.append(path)\n"
    "\n"
    "\n"
    "def compat():\n"
    "    try:\n"
    "        import idj_compat\n"
    "    except ModuleNotFoundError as e:\n"
    "        if e.name != \"idj_compat\":\n"
    "            traceback.print_exc()\n"
    "        return\n"
    "    except Exception:\n"
    "        traceback.print_exc()\n"
    "        return\n"
    "    try:\n"
    "        idj_compat.install()\n"
    "    except Exception:\n"
    "        traceback.print_exc()\n"
    "    flush()\n";

#endif
